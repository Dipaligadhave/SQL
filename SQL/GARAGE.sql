---Q42 Write a query to get details of employee and provide rating on basis of  maximum services provide by employee  .Note (rating should be like A,B,C,D)
SELECT e.eid,e.ename,e.ejob,NVL(e.esal,0) AS salary,sc.service_count,
CASE 
    WHEN r.rnk = 1 THEN 'A'
     WHEN r.rnk = 2 THEN 'B'
      WHEN r.rnk = 3 THEN 'C'
      ELSE 'D'
    END AS rating
FROM employees e
JOIN (SELECT eid,COUNT(*) AS service_count,
DENSE_RANK() OVER (ORDER BY COUNT(*) DESC) AS rnk FROM ser_det
GROUP BY eid
)sc
 ON e.eid = sc.eid
JOIN (SELECT DISTINCT eid,DENSE_RANK() OVER (ORDER BY COUNT(*) DESC) AS rnk FROM ser_det
GROUP BY eid
) r
 ON sc.eid = r.eid
ORDER BY sc.service_count DESC;

